# =============================================================

def emit(source: str, filename: str = "<source>") -> tuple:
    """
    Transpile Skev source code to Python source code.

    Args:
        source:   complete Skev source code
        filename: for error messages (optional)

    Returns:
        (python_code, errors)
        python_code: Python source code string (ready to exec or run)
        errors:      list of parse/lex errors (empty if source is valid)

    Example:
        code, errors = emit('entity Player >> health :: int = 100 << Player')
        if not errors:
            exec(code)              # runs the code
            p = Player()            # creates a Player instance
            print(p.health)         # prints 100
    """
    program, errors = parse(source, filename)
    if errors:
        return "", errors
    emitter = Emitter(program)
    python_code = emitter.emit()
    return python_code, []
